/** 返信を書くときに、AIに渡す内容（プロフィール＋手紙） */
export function buildReplyInput(profile, letter) {
  const profileLines = PROFILE_FIELDS
    .map(f => `・${f.label}：${profile[f.key] ? profile[f.key] : '（未記入）'}`)
    .join('\n');

  return `以下は、3年前の自分から届いたものです。3年後の自分として、心のこもった返信を書いてください。

【3年前の自分が想像した「3年後の自分のプロフィール」】
${profileLines}

【3年前の自分から届いた手紙】
---
${letter}
---`;
}
